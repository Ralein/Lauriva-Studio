  // native ML runtime, and no network call — this is the "compact classifier
  // over stylometric/linguistic features" approach that published research
  // (e.g. arXiv:2511.21744, NEULIF) shows reaches near-transformer accuracy
  // at negligible size and compute cost, which is what a strict mobile app
