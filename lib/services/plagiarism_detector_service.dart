  /// Extracts the fixed-order raw (unnormalized) stylometric feature vector
  /// used by the on-device ML classifier. Exposed (not private) so the
  /// offline training script can call the exact same code the app runs.
  @visibleForTesting
  List<double> extractFeatureVector(String rawText) {
    final text = rawText.trim();
    final sentences = TextForensicsLexicons.splitSentences(text);
    final words = TextForensicsLexicons.extractWords(text);
    final totalWords = max(words.length, 1);

    if (sentences.isEmpty || words.isEmpty) {
      return List<double>.filled(mlFeatureNames.length, 0.0);
    }

    final sentenceLengths = sentences.map((s) => TextForensicsLexicons.extractWords(s).length).toList();
    final avgSentenceLength = sentenceLengths.reduce((a, b) => a + b) / sentenceLengths.length;
    double variance = 0.0;
    for (final len in sentenceLengths) {
      variance += pow(len - avgSentenceLength, 2);
    }
    final stdDev = sqrt(variance / sentenceLengths.length);
    final burstiness = avgSentenceLength > 0 ? (stdDev / avgSentenceLength) : 1.0;

    final trigrams = TextForensicsLexicons.extractNgrams(words, 3);
    final fourGrams = TextForensicsLexicons.extractNgrams(words, 4);
    final repeatedNgrams = TextForensicsLexicons.findRepeatedNgrams(fourGrams.isNotEmpty ? fourGrams : trigrams);
    final ngramOverlapScore = ((repeatedNgrams.length * 4) / totalWords * 100).clamp(0.0, 100.0);

    final uniqueWords = words.map((w) => w.toLowerCase()).toSet();
    final ttr = (uniqueWords.length / totalWords) * 100.0;
    final guiraudR = uniqueWords.length / sqrt(totalWords);
    final lexicalRichness = ((ttr * 0.5) + (min(guiraudR * 10.0, 100.0) * 0.5)).clamp(0.0, 100.0);

    final stockWordCount = words.where((w) => TextForensicsLexicons.aiStockWords.contains(w.toLowerCase())).length;
    final stockWordDensity = stockWordCount / totalWords * 100.0;

    final lowerText = text.toLowerCase();
    final boilerplateCount = TextForensicsLexicons.academicBoilerplates.where(lowerText.contains).length.toDouble();

    final emDashRate = TextForensicsLexicons.emDashPattern.allMatches(text).length / sentences.length;
    final markdownCount = (TextForensicsLexicons.markdownBlockPattern.allMatches(text).length +
            TextForensicsLexicons.markdownBoldPattern.allMatches(text).length)
        .toDouble();

    final transitionOpenerCount = sentences.where((s) {
      final lower = s.trimLeft().toLowerCase();
      return TextForensicsLexicons.transitionOpeners.any((t) => lower.startsWith('$t,') || lower.startsWith('$t '));
    }).length;
    final transitionOpenerRatio = transitionOpenerCount / sentences.length;

    final avgWordLength = words.map((w) => w.length).reduce((a, b) => a + b) / totalWords;

    final punctuationMatches = RegExp(r'[.,;:!?()\-—]').allMatches(text).map((m) => m.group(0)!).toList();
    final punctuationDiversity =
        punctuationMatches.isEmpty ? 0.0 : punctuationMatches.toSet().length / punctuationMatches.length;

    final functionWordCount = words.where((w) => TextForensicsLexicons.functionWords.contains(w.toLowerCase())).length;
    final functionWordRatio = functionWordCount / totalWords * 100.0;

    double patternTellScore = 0.0;
    for (final pattern in _aiPatterns) {
      final count = pattern.regex.allMatches(text).length;
      if (count > 0) patternTellScore += pattern.weight * min(count, 3);
    }

    return [
      burstiness,
      avgSentenceLength,
      lexicalRichness,
      ngramOverlapScore,
      stockWordDensity,
      boilerplateCount,
      emDashRate,
      markdownCount,
      transitionOpenerRatio,
      avgWordLength,
      punctuationDiversity,
      functionWordRatio,
      patternTellScore,
    ];
  }

  /// Runs the trained logistic-regression classifier over [rawText] and
  /// returns an AI-likelihood score in the 0-100 range.
  @visibleForTesting
  double mlClassifierScore(String rawText) {
    final features = extractFeatureVector(rawText);
    double z = _mlBias;
    for (int i = 0; i < features.length; i++) {
      final normalized = _mlFeatureStdDevs[i] == 0
          ? 0.0
          : (features[i] - _mlFeatureMeans[i]) / _mlFeatureStdDevs[i];
      z += _mlWeights[i] * normalized;
    }
    final sigmoid = 1.0 / (1.0 + exp(-z));
    return (sigmoid * 100.0).clamp(0.0, 100.0);
  }
