/// Client-side ML & NLP engine for detecting AI-generated text,
/// algorithmic repetition, and plagiarism patterns with Hugging Face integration.
class PlagiarismDetectorService {
  final AiForensicService _aiForensics;
  final SourcePlagiarismService _sourcePlagiarism;
  final ForensicEngine _forensicEngine;
  final ForensicCoordinatorService _coordinator;

  PlagiarismDetectorService({
    AiForensicService? aiForensics,
    SourcePlagiarismService? sourcePlagiarism,
    ForensicEngine? forensicEngine,
    ForensicCoordinatorService? coordinator,
  })  : _aiForensics = aiForensics ?? AiForensicService(),
        _sourcePlagiarism = sourcePlagiarism ?? SourcePlagiarismService(),
        _forensicEngine = forensicEngine ??
            ForensicEngine(
              aiService: aiForensics ?? AiForensicService(),
              sourceService: sourcePlagiarism ?? SourcePlagiarismService(),
            ),
        _coordinator = coordinator ??
            ForensicCoordinatorService(
              engine: forensicEngine ??
                  ForensicEngine(
                    aiService: aiForensics ?? AiForensicService(),
                    sourceService: sourcePlagiarism ?? SourcePlagiarismService(),
                  ),
            );

  AiForensicService get aiForensics => _aiForensics;
  ForensicEngine get forensicEngine => _forensicEngine;
  ForensicCoordinatorService get coordinator => _coordinator;

  /// Performs a full Forensic Engine 3.5 multi-dimensional scan with chunk progress callback.
  Future<ForensicReport> analyzeForensic(
    String rawText, {
    ForensicScanMode mode = ForensicScanMode.fullForensic,
    ForensicSensitivity sensitivity = ForensicSensitivity.balanced,
    bool enableOnlineSearch = true,
    bool enableWatermarkDetection = true,
    bool enableHomoglyphDetection = true,
    void Function(ForensicProgress)? onProgress,
  }) async {
    return _coordinator.coordinate(
      text: rawText,
      mode: mode,
      sensitivity: sensitivity,
      enableOnlineSearch: enableOnlineSearch,
      enableWatermarkDetection: enableWatermarkDetection,
      enableHomoglyphDetection: enableHomoglyphDetection,
      onProgress: onProgress,
    );
  }

  /// Performs cloud LLM-backed forensic audit with online literature search.
  /// Requires active API key and internet connectivity; never falls back to offline engine.
  Future<ForensicReport> analyzeForensicWithLlm({
    required String text,
    required LlmService llmService,
    required LlmProvider provider,
    required String apiKey,
    required String model,
    Map<String, String>? allConfiguredKeys,
    String? customBaseUrl,
    ForensicScanMode mode = ForensicScanMode.fullForensic,
    ForensicSensitivity sensitivity = ForensicSensitivity.balanced,
    bool enableOnlineSearch = true,
    void Function(ForensicProgress)? onProgress,
  }) async {
    return _coordinator.coordinateWithLlm(
      text: text,
      llmService: llmService,
      provider: provider,
      apiKey: apiKey,
      model: model,
      allConfiguredKeys: allConfiguredKeys,
      customBaseUrl: customBaseUrl,
      mode: mode,
      sensitivity: sensitivity,
      enableOnlineSearch: enableOnlineSearch,
      onProgress: onProgress,
    );
  }

  // Regular expression patterns for common AI stylistic tells
  static final List<_PatternTell> _aiPatterns = [
    _PatternTell(
      name: 'Not X but Y contrast',
      regex: RegExp(
        r'\b(?:it(?:\x27s|\s+is)\s+not\s+(?:just|only|merely)\s+[^,.?!]+,?\s*but\b|not\s+(?:only|just|merely)\s+[^,.?!]+,?\s*but\s+also\b|not\s+[^,.?!]+,?\s*it(?:\x27s|\s+is)\s+[^,.?!]+)',
        caseSensitive: false,
      ),
      weight: 16.0,
      description: 'Staged contrast formula commonly generated by LLMs to manufacture rhetorical weight.',
    ),
    _PatternTell(
      name: 'Staged run-up / candor opener',
      regex: RegExp(
        r'\b(?:let(?:\x27s|\s+us)\s+(?:dive\s+in|explore|break\s+this\s+down)|here(?:\x27s|\s+is)\s+what\s+you\s+need\s+to\s+know|without\s+further\s+ado|honestly\?|look,?\s+|here(?:\x27s|\s+is)\s+the\s+thing)\b',
        caseSensitive: false,
      ),
      weight: 18.0,
      description: 'Chatbot-style conversational preamble before stating a basic claim.',
    ),
    _PatternTell(
      name: 'Staged profundity / aphorism',
      regex: RegExp(
        r'\b(?:at\s+its\s+core|in\s+reality|what\s+really\s+matters|the\s+heart\s+of\s+the\s+matter|is\s+the\s+(?:currency|architecture|language)\s+of|becomes\s+a\s+trap)\b',
        caseSensitive: false,
      ),
      weight: 14.0,
      description: 'Dressing ordinary facts as universal truths or pseudo-philosophical aphorisms.',
    ),
    _PatternTell(
      name: 'Defensive disclaimer / arguing with no one',
      regex: RegExp(
        r'\b(?:to\s+be\s+clear|don(?:\x27t|\s+not)\s+get\s+me\s+wrong|this\s+is\s+not\s+to\s+say|some\s+might\s+say|one\s+might\s+be\s+tempted\s+to)\b',
        caseSensitive: false,
      ),
      weight: 12.0,
      description: 'Unprompted rebuttal of non-existent objections characteristic of draft models.',
    ),
    _PatternTell(
      name: 'Inflated significance phrase',
      regex: RegExp(
        r'\b(?:stands\s+as\s+a\s+testament|indelible\s+mark|evolving\s+landscape|pivotal\s+moment|setting\s+the\s+stage\s+for|plays\s+a\s+(?:crucial|pivotal|key)\s+role)\b',
        caseSensitive: false,
      ),
      weight: 15.0,
      description: 'Hyperbolic framing attributing historical or monumental importance to mundane facts.',
    ),
    _PatternTell(
      name: 'Shallow -ing participle tail',
      regex: RegExp(
        r',\s+(?:highlighting|underscoring|emphasizing|ensuring|reflecting|symbolizing|fostering|showcasing)\b',
        caseSensitive: false,
      ),
      weight: 10.0,
      description: 'Participle phrase bolted onto the end of a sentence to artificially deepen tone.',
    ),
    _PatternTell(
      name: 'Forced triad of adjectives or nouns',
      regex: RegExp(
        r'\b([a-zA-Z]{3,}),\s+([a-zA-Z]{3,}),\s+and\s+([a-zA-Z]{3,})\b',
        caseSensitive: false,
      ),
      weight: 8.0,
      description: 'Rhythmic grouping into threes regardless of whether meaning demands it.',
    ),
    _PatternTell(
      name: 'Chatbot wrapper residue',
      regex: RegExp(
        r'\b(?:as\s+an\s+ai|certainly!|of\s+course!|i\s+hope\s+this\s+helps|great\s+question!|would\s+you\s+like\s+me\s+to)\b',
        caseSensitive: false,
      ),
      weight: 25.0,
      description: 'Direct conversational chat residue from AI models.',
    ),
  ];

  /// Asynchronously analyzes text.
  /// Offloads execution to a background isolate via [compute] for texts
  /// exceeding 500 characters, preventing UI frame drops on long documents.
  Future<PlagiarismReport> analyzeAsync(String rawText) async {
    final text = rawText.trim();
    if (text.isEmpty || text.length < 500) {
      return analyze(text);
    }
    return compute(_isolateAnalyzeEntryPoint, text);
  }

  static PlagiarismReport _isolateAnalyzeEntryPoint(String text) {
    return PlagiarismDetectorService().analyze(text);
  }

  /// Analyzes text and returns a comprehensive PlagiarismReport
  PlagiarismReport analyze(String rawText) {
    final text = rawText.trim();
    if (text.isEmpty) {
      return PlagiarismReport(
        overallScore: 0.0,
        riskLevel: PlagiarismRiskLevel.clean,
        humanScore: 100.0,
        burstinessScore: 1.0,
        predictabilityScore: 0.0,
        lexicalRichness: 100.0,
        ngramOverlapScore: 0.0,
        repeatedNgrams: const [],
        detectedTells: const [],
        sentences: const [],
        uncertaintyScore: 0.0,
        confidenceLevel: 'Insufficient Evidence',
        authorshipBadge: 'HUMAN WRITTEN',
        defensibleSummary: 'No text provided.',
      );
    }

    // 1. Sentence Segmentation
    final sentences = TextForensicsLexicons.splitSentences(text);
    if (sentences.isEmpty) {
      return PlagiarismReport(
        overallScore: 0.0,
        riskLevel: PlagiarismRiskLevel.clean,
        humanScore: 100.0,
        burstinessScore: 1.0,
        predictabilityScore: 0.0,
        lexicalRichness: 100.0,
        ngramOverlapScore: 0.0,
        repeatedNgrams: const [],
        detectedTells: const [],
        sentences: const [],
        uncertaintyScore: 0.0,
        confidenceLevel: 'Insufficient Evidence',
        authorshipBadge: 'HUMAN WRITTEN',
        defensibleSummary: 'No sentences detected.',
      );
    }

    // 2. Word Tokenization & N-Gram Extraction (architshukla/Plagiarism-Checker inspiration)
    final words = TextForensicsLexicons.extractWords(text);
    final totalWords = max(words.length, 1);
    final trigrams = TextForensicsLexicons.extractNgrams(words, 3);
    final fourGrams = TextForensicsLexicons.extractNgrams(words, 4);

    // 3. Repeated N-Grams (internal formulaic repetition)
    final repeatedNgrams = TextForensicsLexicons.findRepeatedNgrams(fourGrams.isNotEmpty ? fourGrams : trigrams);
    final ngramOverlapRatio = (repeatedNgrams.length * 4) / totalWords;
    final ngramOverlapScore = (ngramOverlapRatio * 100).clamp(0.0, 100.0);

    // 4. Lexical Richness (Type-Token Ratio & Unique Roots)
    final uniqueWords = words.map((w) => w.toLowerCase()).toSet();
    final ttr = (uniqueWords.length / totalWords) * 100.0;
    // Guiraud's R index: unique words / sqrt(total words)
    final guiraudR = uniqueWords.length / sqrt(totalWords);
    final lexicalRichness = ((ttr * 0.5) + (min(guiraudR * 10.0, 100.0) * 0.5)).clamp(0.0, 100.0);

    // 5. Burstiness Analysis (Variance of Sentence Lengths)
    final sentenceLengths = sentences.map((s) => TextForensicsLexicons.extractWords(s).length).toList();
    final avgLength = sentenceLengths.reduce((a, b) => a + b) / sentenceLengths.length;
    double variance = 0.0;
    for (final len in sentenceLengths) {
      variance += pow(len - avgLength, 2);
    }
    final stdDev = sqrt(variance / sentenceLengths.length);
    // Coefficient of variation: stdDev / avgLength.
    // Human text typically has CV > 0.5, while AI text has CV ~ 0.15 - 0.35.
    final burstiness = avgLength > 0 ? (stdDev / avgLength) : 1.0;

    // 6. AI Pattern & Tell Detection across the entire text
    final detectedTellsSet = <String>{};
    double totalTellScore = 0.0;

    for (final pattern in _aiPatterns) {
      final matches = pattern.regex.allMatches(text);
      if (matches.isNotEmpty) {
        final count = matches.length;
        detectedTellsSet.add('${pattern.name} ($count occurrence${count > 1 ? "s" : ""})');
        totalTellScore += pattern.weight * min(count, 3);
      }
    }

    // Stock words check
    int stockWordCount = 0;
    final foundStockWords = <String>{};
    for (final word in words) {
      final lower = word.toLowerCase();
      if (TextForensicsLexicons.aiStockWords.contains(lower)) {
        stockWordCount++;
        foundStockWords.add(lower);
      }
    }
    if (foundStockWords.isNotEmpty) {
      detectedTellsSet.add(
        'Overused AI vocabulary: ${foundStockWords.take(5).join(", ")} ($stockWordCount count)',
      );
      totalTellScore += min(stockWordCount * 4.0, 24.0);
    }

    // Academic & Plagiarism Boilerplate check
    final flaggedBoilerplates = <String>[];
    final lowerText = text.toLowerCase();
    for (final bp in TextForensicsLexicons.academicBoilerplates) {
      if (lowerText.contains(bp)) {
        flaggedBoilerplates.add(bp);
      }
    }
    if (flaggedBoilerplates.isNotEmpty) {
      detectedTellsSet.add(
        'Boilerplate phrases: ${flaggedBoilerplates.take(3).join(", ")} (${flaggedBoilerplates.length} found)',
      );
      totalTellScore += min(flaggedBoilerplates.length * 6.0, 24.0);
    }

    // Em dash overuse — modern LLMs reach for interruptive/appositive em
    // dashes far more than natural prose does; two or more, at a rate above
    // roughly one per three sentences, is a meaningful signal.
    final emDashCount = TextForensicsLexicons.emDashPattern.allMatches(text).length;
    if (sentences.isNotEmpty && emDashCount >= 2) {
      final emDashRate = emDashCount / sentences.length;
      if (emDashRate > 0.3) {
        detectedTellsSet.add(
          'Em dash overuse: $emDashCount occurrence${emDashCount > 1 ? "s" : ""} '
          '(${emDashRate.toStringAsFixed(2)} per sentence)',
        );
        totalTellScore += min(emDashCount * 5.0, 20.0);
      }
    }

    // Unstripped markdown formatting (bullets, numbered lists, headers, bold)
    // bleeding into prose — a tell that raw model output was pasted in
    // without cleanup.
    final markdownCount = TextForensicsLexicons.markdownBlockPattern.allMatches(text).length +
        TextForensicsLexicons.markdownBoldPattern.allMatches(text).length;
    if (markdownCount > 0) {
      detectedTellsSet.add(
        'Unstripped markdown formatting: $markdownCount occurrence${markdownCount > 1 ? "s" : ""} '
        '(bullets, headers, or bold)',
      );
      totalTellScore += min(markdownCount * 8.0, 24.0);
    }

    // Formal transition-word openers ("Moreover,", "Furthermore,", ...) —
    // human writers vary sentence openers far more than models, which lean
    // on a small, formal connector vocabulary.
    int transitionOpenerCount = 0;
    for (final sentenceText in sentences) {
      final lower = sentenceText.trimLeft().toLowerCase();
      if (TextForensicsLexicons.transitionOpeners.any((t) => lower.startsWith('$t,') || lower.startsWith('$t '))) {
        transitionOpenerCount++;
      }
    }
    if (sentences.length >= 3 && (transitionOpenerCount / sentences.length) > 0.25) {
      detectedTellsSet.add(
        'Formal transition-word openers in $transitionOpenerCount of ${sentences.length} sentences',
      );
      totalTellScore += min(transitionOpenerCount * 6.0, 24.0);
    }

    // 7. Per-Sentence Audit
    final sentenceAudits = <SentenceAudit>[];
    double sumSentenceAi = 0.0;

    for (int i = 0; i < sentences.length; i++) {
      final sentenceText = sentences[i];
      final sWords = TextForensicsLexicons.extractWords(sentenceText);
      final sWordCount = sWords.length;
      final sTells = <String>[];
      double sScore = 15.0; // Baseline prior

      // Sentence pattern check
      for (final pattern in _aiPatterns) {
        if (pattern.regex.hasMatch(sentenceText)) {
          sTells.add(pattern.name);
          sScore += pattern.weight;
        }
      }

      // Sentence stock words check
      for (final w in sWords) {
        final lw = w.toLowerCase();
        if (TextForensicsLexicons.aiStockWords.contains(lw)) {
          sTells.add('AI word: "$lw"');
          sScore += 8.0;
        }
      }

      // Sentence length uniformity penalty (AI sentences hover predictably around 16-22 words)
      final lengthDiffFromAvg = (sWordCount - avgLength).abs();
      if (sWordCount >= 14 && sWordCount <= 22 && lengthDiffFromAvg < 3) {
        sScore += 6.0;
      }

      // Em dash / unstripped markdown residue within this specific sentence
      if (TextForensicsLexicons.emDashPattern.hasMatch(sentenceText)) {
        sTells.add('Em dash usage');
        sScore += 4.0;
      }
      if (TextForensicsLexicons.markdownBlockPattern.hasMatch(sentenceText) || TextForensicsLexicons.markdownBoldPattern.hasMatch(sentenceText)) {
        sTells.add('Markdown formatting artifact');
        sScore += 8.0;
      }
      final sLower = sentenceText.trimLeft().toLowerCase();
      if (TextForensicsLexicons.transitionOpeners.any((t) => sLower.startsWith('$t,') || sLower.startsWith('$t '))) {
        sTells.add('Formal transition opener');
        sScore += 5.0;
      }

      final clampedSentenceScore = sScore.clamp(0.0, 100.0);
      final sRisk = PlagiarismRiskLevel.fromScore(clampedSentenceScore);
      sentenceAudits.add(
        SentenceAudit(
          index: i,
          text: sentenceText,
          aiProbability: clampedSentenceScore,
          riskLevel: sRisk,
          detectedTells: sTells,
          wordCount: sWordCount,
          burstinessDelta: lengthDiffFromAvg,
        ),
      );

      sumSentenceAi += clampedSentenceScore;
    }

    // 8. Predictability Index (Composite of N-gram overlap + Low lexical variety + Uniformity)
    final avgSentenceAi = sentences.isNotEmpty ? (sumSentenceAi / sentences.length) : 0.0;
    final lowBurstinessPenalty = burstiness < 0.45 ? ((0.45 - burstiness) * 60.0).clamp(0.0, 30.0) : 0.0;
    final lowLexicalPenalty = lexicalRichness < 60.0 ? ((60.0 - lexicalRichness) * 0.4).clamp(0.0, 20.0) : 0.0;
    final tellScoreNormalized = min((totalTellScore / (totalWords / 15.0)) * 25.0, 50.0);

    final predictabilityScore = (
      (ngramOverlapScore * 0.3) +
      (tellScoreNormalized * 0.4) +
      (lowBurstinessPenalty * 0.3)
    ).clamp(0.0, 100.0);

    // 9. Composite Overall AI Plagiarism Score
    // Balances sentence-level audits, global tells, burstiness, and formulaic n-grams
    double rawOverallScore = (avgSentenceAi * 0.4) +
        (tellScoreNormalized * 0.3) +
        (lowBurstinessPenalty * 0.15) +
        (ngramOverlapScore * 0.1) +
        (lowLexicalPenalty * 0.05);

    // If human burstiness is high (CV >= 0.75) and tells are zero, give strong natural bonus
    if (burstiness >= 0.75 && detectedTellsSet.isEmpty) {
      rawOverallScore *= 0.55;
    }

    // If strong chatbot tells exist, minimum score is high
    if (text.toLowerCase().contains('as an ai') || text.toLowerCase().contains('i hope this helps')) {
      rawOverallScore = max(rawOverallScore, 92.0);
    }

    // 10. On-device ML ensemble — blend the trained stylometric classifier's
    // independent opinion into the rule-based score.
    // Integrate Forensics Engine v2 (38-feature calibrated ensemble) with v1 baseline.
    final forensicResult = _aiForensics.auditText(text);
    final plagiarismResult = _sourcePlagiarism.analyzeText(text);

    final v1Score = mlClassifierScore(text);
    final v2Score = forensicResult.aiProbability;
    final mlScore = (v2Score * 0.60 + v1Score * 0.40);

    if (mlScore >= 50.0) {
      detectedTellsSet.add('On-device ML classifier: ${mlScore.toStringAsFixed(1)}% AI confidence');
    }
    for (final signal in forensicResult.detectedSignals) {
      if (signal.score > 25.0) {
        detectedTellsSet.add('${signal.family}: ${signal.name}');
      }
    }
    for (final match in plagiarismResult.sourceMatches) {
      detectedTellsSet.add(
        'Literature match: "${match.sourceTitle}" (${match.similarityPercent.toStringAsFixed(0)}% match)',
      );
    }

    final blendedScore = (rawOverallScore * 0.60) + (mlScore * 0.40);
    final finalScore = blendedScore.clamp(0.0, 100.0);
    final risk = PlagiarismRiskLevel.fromScore(finalScore);

    return PlagiarismReport(
      overallScore: finalScore,
      riskLevel: risk,
      humanScore: (100.0 - finalScore).clamp(0.0, 100.0),
      burstinessScore: burstiness,
      predictabilityScore: predictabilityScore,
      lexicalRichness: lexicalRichness,
      ngramOverlapScore: ngramOverlapScore,
      repeatedNgrams: repeatedNgrams.isNotEmpty ? repeatedNgrams : plagiarismResult.repeatedNgrams,
      detectedTells: detectedTellsSet.toList(),
      sentences: sentenceAudits,
      // Owned by SourcePlagiarismService — kept decoupled from the AI-authorship
      // score above rather than re-deriving a near-duplicate value inline.
      plagiarismRiskScore: plagiarismResult.plagiarismRiskScore,
      flaggedBoilerplates: flaggedBoilerplates,
      uncertaintyScore: forensicResult.uncertainty,
      confidenceLevel: forensicResult.confidenceLevel.label,
      authorshipBadge: forensicResult.authorshipClass.badge,
      defensibleSummary: forensicResult.defensibleSummary,
    );
  }

  /// Analyzes text using Hugging Face neural classifier model (e.g. Hello-SimpleAI/chatgpt-detector-roberta)
  /// with graceful, zero-failure fallback to local on-device NLP engine.
  Future<PlagiarismReport> analyzeWithHuggingFace({
    required String text,
    String? apiKey,
    String model = 'Hello-SimpleAI/chatgpt-detector-roberta',
    http.Client? client,
    bool fallbackToOffline = false,
  }) async {
    final localReport = analyze(text);
    if (text.trim().isEmpty) return localReport;

    final httpClient = client ?? http.Client();
    try {
      final truncated = text.length > 1500 ? text.substring(0, 1500) : text;
      final url = Uri.parse('https://api-inference.huggingface.co/models/$model');
      final headers = <String, String>{
        'Content-Type': 'application/json',
      };
      if (apiKey != null && apiKey.trim().isNotEmpty) {
        headers['Authorization'] = 'Bearer ${apiKey.trim()}';
      }

      final response = await httpClient
          .post(
            url,
            headers: headers,
            body: jsonEncode({'inputs': truncated}),
          )
          .timeout(const Duration(seconds: 10));

      if (response.statusCode == 200) {
        final decoded = jsonDecode(response.body);
        if (decoded is List && decoded.isNotEmpty) {
          final list = decoded.first is List ? (decoded.first as List) : decoded;
          double? hfAiProbability;
          double? hfHumanProbability;

          for (final item in list) {
            if (item is Map<String, dynamic>) {
              final label = (item['label'] as String? ?? '').toLowerCase();
              final score = (item['score'] as num? ?? 0.0).toDouble() * 100.0;

              if (label.contains('chatgpt') ||
                  label.contains('fake') ||
                  label.contains('ai') ||
                  label == 'label_1') {
                hfAiProbability = score;
              } else if (label.contains('human') ||
                  label.contains('real') ||
                  label == 'label_0') {
                hfHumanProbability = score;
              }
            }
          }

          final resolvedAiProb = hfAiProbability ??
              (hfHumanProbability != null ? (100.0 - hfHumanProbability) : null);

          if (resolvedAiProb != null) {
            // Ensemble: Blend deep neural classifier (60%) with structural NLP metrics (40%)
            final blendedOverall = (resolvedAiProb * 0.60 + localReport.overallScore * 0.40).clamp(0.0, 100.0);
            final blendedRisk = PlagiarismRiskLevel.fromScore(blendedOverall);
            final updatedTells = [
              'Hugging Face RoBERTa: ${resolvedAiProb.toStringAsFixed(1)}% AI confidence',
              ...localReport.detectedTells,
            ];

            return PlagiarismReport(
              overallScore: blendedOverall,
              riskLevel: blendedRisk,
              humanScore: (100.0 - blendedOverall).clamp(0.0, 100.0),
              burstinessScore: localReport.burstinessScore,
              predictabilityScore: localReport.predictabilityScore,
              lexicalRichness: localReport.lexicalRichness,
              ngramOverlapScore: localReport.ngramOverlapScore,
              repeatedNgrams: localReport.repeatedNgrams,
              detectedTells: updatedTells,
              sentences: localReport.sentences,
              modelSource: 'Hugging Face ($model)',
              plagiarismRiskScore: localReport.plagiarismRiskScore,
              flaggedBoilerplates: localReport.flaggedBoilerplates,
              uncertaintyScore: localReport.uncertaintyScore,
              confidenceLevel: localReport.confidenceLevel,
              authorshipBadge: localReport.authorshipBadge,
              defensibleSummary: localReport.defensibleSummary,
            );
          }
        }
      } else {
        AppLogger.warn(
          'Hugging Face inference returned status ${response.statusCode}: ${response.body}',
          'Plagiarism',
        );
        if (!fallbackToOffline) {
          throw LlmApiException('Hugging Face inference failed (${response.statusCode}): ${response.body}. Offline engine is disabled.');
        }
      }
    } catch (e) {
      AppLogger.warn('Hugging Face detector error: $e', 'Plagiarism');
      if (fallbackToOffline) return localReport;
      if (e is LlmApiException) rethrow;
      throw LlmApiException('Hugging Face inference failed: $e. Offline engine is disabled.');
    } finally {
      if (client == null) {
        httpClient.close();
      }
    }

    if (!fallbackToOffline) {
      throw LlmApiException('Hugging Face returned an invalid response. Offline engine is disabled.');
    }
    return localReport;
  }

  /// Compares original vs transformed text and returns a comparative report
  PlagiarismReport compareTransform({
    required String originalText,
    required String transformedText,
    String modelSource = 'Lauriva Forensic Engine',
  }) {
    final originalReport = analyze(originalText);
    final transformedReport = analyze(transformedText);

    return originalReport.withFix(
      fixedText: transformedText,
      fixedScore: transformedReport.overallScore,
      fixedRiskLevel: transformedReport.riskLevel,
    );
  }

  // --- On-device stylometric ML classifier ---
